"""
Layer 2 - Download the CIFAKE dataset and export demo samples.

Pulls the CIFAKE train/test parquet files from Hugging Face (public, no login
required) into data/, then exports a few REAL and FAKE sample images into
data/samples/ so you can demo the detector in the web app.

CIFAKE: 60k REAL images (from CIFAR-10) + 60k FAKE images (generated by a
Stable Diffusion model). Labels in the parquet: 0 = FAKE, 1 = REAL.

Run:  py layer2_detector/download_data.py
"""

import os
import io

import requests
import pandas as pd
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(HERE, "data")
SAMPLES_DIR = os.path.join(DATA_DIR, "samples")

BASE_URL = ("https://huggingface.co/datasets/dragonintelligence/"
            "CIFAKE-image-dataset/resolve/main/data/")
FILES = {
    "train.parquet": "train-00000-of-00001.parquet",
    "test.parquet": "test-00000-of-00001.parquet",
}


def download():
    os.makedirs(DATA_DIR, exist_ok=True)
    for local, remote in FILES.items():
        path = os.path.join(DATA_DIR, local)
        if os.path.exists(path):
            print(f"  already have {local}")
            continue
        print(f"  downloading {local} ...")
        resp = requests.get(BASE_URL + remote, timeout=600)
        resp.raise_for_status()
        with open(path, "wb") as fh:
            fh.write(resp.content)
        print(f"    saved {len(resp.content) // 1024} KB")


def export_samples(n_per_class=8):
    os.makedirs(SAMPLES_DIR, exist_ok=True)
    df = pd.read_parquet(os.path.join(DATA_DIR, "test.parquet"))
    for label, name in [(1, "real"), (0, "fake")]:
        subset = df[df.label == label].head(n_per_class)
        for i, (_, row) in enumerate(subset.iterrows(), start=1):
            im = Image.open(io.BytesIO(row["image"]["bytes"])).convert("RGB")
            # Upscale (nearest) so 32x32 thumbnails are visible in a browser.
            im.resize((128, 128), Image.NEAREST).save(
                os.path.join(SAMPLES_DIR, f"{name}_{i}.png")
            )
    print(f"  exported {n_per_class} real + {n_per_class} fake samples -> {SAMPLES_DIR}")


if __name__ == "__main__":
    print("Downloading CIFAKE ...")
    download()
    print("Exporting demo samples ...")
    export_samples()
    print("Done.")
